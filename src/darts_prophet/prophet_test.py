import pandas as pd
from darts.timeseries import TimeSeries
from darts.models import Prophet
from darts.metrics import smape, rmse
import matplotlib.pyplot as plt

from data_processing import load_data, build_series

# ── CONFIG ─────────────────────────────────────────────────────────────────────
CSV_PATH      = "data/untill_exports_tables.csv"   # <-- change this to your file path
RESULT_PATH  = "experiments/"
TARGET_COL    = "price"
DATE_COL      = "date"
HOUR_COL      = "hour"
FORECAST_HORIZON = 24             # how many hours ahead to forecast
TEST_SIZE        = 48             # last N hours held out for evaluation
# ───────────────────────────────────────────────────────────────────────────────


def run_prophet(series: TimeSeries):
    # ── Train / test split ───────────────────────────────────────────────────
    train, test = series[:-TEST_SIZE], series[-TEST_SIZE:]
    print(f"\n📊 Train size: {len(train)}  |  Test size: {len(test)}")

    # ── Fit Prophet ──────────────────────────────────────────────────────────
    model = Prophet(
        seasonality_mode="multiplicative",   # try "additive" if prices are low/stable
        yearly_seasonality=True,
        weekly_seasonality=True,
        daily_seasonality=True,
    )

    print("⏳ Fitting Prophet model…")
    model.fit(train)

    # ── In-sample backtest on test set ───────────────────────────────────────
    print("🔮 Generating forecast…")
    pred = model.predict(len(test))

    # ── Metrics ──────────────────────────────────────────────────────────────
    smape_val = smape(test, pred)
    rmse_val = rmse(test, pred)
    print(f"\n📈 Test SMAPE : {smape_val:.2f}%")
    print(f"📉 Test RMSE : {rmse_val:.4f}")

    # ── Future forecast beyond the dataset ───────────────────────────────────
    future_model = Prophet(
        seasonality_mode="multiplicative",
        yearly_seasonality=True,
        weekly_seasonality=True,
        daily_seasonality=True,
    )
    future_model.fit(series)
    future_pred = future_model.predict(FORECAST_HORIZON)

    # ── Plot ─────────────────────────────────────────────────────────────────
    fig, axes = plt.subplots(2, 1, figsize=(14, 8))
    fig.suptitle("Darts – Prophet Forecast on 'price'", fontsize=14, fontweight="bold")

    # Plot 1: backtest
    ax1 = axes[0]
    train[-7 * 24:].plot(ax=ax1, label="Train (last 7 days)")   # show last week of train
    test.plot(ax=ax1, label="Actual (test)")
    pred.plot(ax=ax1, label="Predicted (test)", low_quantile=0.1, high_quantile=0.9)
    ax1.set_title("Backtest – Test Set")
    ax1.legend()

    # Plot 2: future forecast
    ax2 = axes[1]
    series[-7 * 24:].plot(ax=ax2, label="Historical (last 7 days)")
    future_pred.plot(ax=ax2, label=f"Future forecast ({FORECAST_HORIZON}h)", low_quantile=0.1, high_quantile=0.9)
    ax2.set_title(f"Future Forecast – Next {FORECAST_HORIZON} Hours")
    ax2.legend()

    plt.tight_layout()
    plt.savefig(f"{RESULT_PATH}prophet_forecast.png", dpi=150)
    print(f"\n💾 Plot saved to {RESULT_PATH}prophet_forecast.png")
    plt.show()

    return pred, future_pred


# ── MAIN ───────────────────────────────────────────────────────────────────────
if __name__ == "__main__":
    df     = load_data(CSV_PATH)
    series = build_series(df)
    pred, future = run_prophet(series)

    # Optional: export forecasts to CSV
    future.to_dataframe().to_csv(f"{RESULT_PATH}future_forecast.csv")
    print(f"💾 Future forecast saved to {RESULT_PATH}future_forecast.csv")